#!/usr/bin/env python3
"""Regroups a generated Achilles model so sibling bodies share SIMD lanes.

    tools/lane_pack_arow.py MODEL_DIR [--archetype NAME]

Achilles runs SIMD lanes across an archetype's copies, so a robot written as
one archetype fills one lane in eight: every body costs a full lane group in
every pass. Sibling leaf bodies that differ only in their values (the 18
rollers on each omni wheel, the armor plates' collision shapes) can instead
be one archetype's copies, attached to their parent joint, with each copy's
values given per copy (`{per_copy: [...]}`, Achilles #36). That runs the
sentry's physics about 3-4x faster and changes nothing it computes.

Rewrites MODEL_DIR/sentry.arow (the model tools/urdf_to_arow.py and
elements_to_arow.py wrote) in place, and writes one .arow per group beside
it, included from it. A group is two or more leaf joints under the same
parent, with the same fields, that no sensor or actuator attaches to (a
part's `attach:` names its joint, and a packed joint's name is gone).
Everything else stays where it was. Running it on an already-packed model
changes nothing.
"""
import argparse
import collections
import os
import sys

import yaml


class _Flow(list):
    """A list YAML writes on one line."""


yaml.add_representer(_Flow, lambda d, x: d.represent_sequence("tag:yaml.org,2002:seq", x, flow_style=True))


def _flow(value):
    """Short numeric lists on one line, as urdf_to_arow.py writes them."""
    if isinstance(value, list):
        if all(not isinstance(x, (list, dict)) for x in value):
            return _Flow(value)
        return [_flow(x) for x in value]
    if isinstance(value, dict):
        return {k: _flow(v) for k, v in value.items()}
    return value


def _attached_joints(model_dir, includes):
    """Every joint a part included from the model attaches to."""
    joints = set()
    for path in includes:
        part = yaml.safe_load(open(os.path.join(model_dir, path)))
        attach = (part or {}).get("attach") or {}
        if attach.get("joint"):
            joints.add(attach["joint"])
    return joints


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model_dir")
    ap.add_argument("--archetype", default="sentry", help="the robot archetype's name (and file stem)")
    args = ap.parse_args()

    path = os.path.join(args.model_dir, f"{args.archetype}.arow")
    doc = yaml.safe_load(open(path))
    joints = doc["joints"]
    includes = list(doc.get("includes") or [])
    attached = _attached_joints(args.model_dir, includes)
    children = collections.Counter(j.get("parent") for j in joints)

    groups = collections.OrderedDict()  # (parent, field names) -> [joint]
    for j in joints:
        if children[j["name"]] or j["name"] in attached or j.get("parent") is None:
            continue
        groups.setdefault((j["parent"], tuple(j["fields"])), []).append(j)
    groups = collections.OrderedDict((k, v) for k, v in groups.items() if len(v) >= 2)
    if not groups:
        print(f"lane_pack_arow: nothing to pack in {path}")
        return 0

    packed = set()
    for n, ((parent, fields), members) in enumerate(groups.items()):
        name = f"{args.archetype}_{parent}_copies" + (f"_{n}" if sum(k[0] == parent for k in groups) > 1 else "")
        values = {}
        for f in fields:
            per = [m["fields"][f] for m in members]
            values[f] = _flow(per[0]) if all(v == per[0] for v in per) else {"per_copy": [_flow(v) for v in per]}
        group = {
            "archetype": name,
            "copies": len(members),
            "attach": {"archetype": doc["archetype"], "joint": parent},
            "joints": [{"name": "body", "parent": None, "fields": values}],
        }
        header = (f"# Generated by tools/lane_pack_arow.py from {os.path.basename(path)}: {len(members)} copies of\n"
                  f"# {members[0]['name']} .. {members[-1]['name']}, one per lane. Don't edit: regenerate it.\n")
        with open(os.path.join(args.model_dir, f"{name}.arow"), "w") as out:
            out.write(header + yaml.dump(group, sort_keys=False, width=200))
        includes.append(f"{name}.arow")
        packed.update(m["name"] for m in members)
        print(f"lane_pack_arow: {name}: {len(members)} copies on {parent}")

    doc["includes"] = includes
    doc["joints"] = [{"name": j["name"], "parent": j.get("parent"), "fields": _flow(j["fields"])}
                     for j in joints if j["name"] not in packed]
    with open(path) as f:
        comments = "".join(line for line in f if line.startswith("#"))
    with open(path, "w") as out:
        out.write(comments + yaml.dump(doc, sort_keys=False, width=200))
    print(f"lane_pack_arow: {doc['archetype']}: {len(doc['joints'])} joints left in {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
