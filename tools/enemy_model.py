#!/usr/bin/env python3
"""Builds the enemy robot (assets/enemy/enemy.yaml) from the doctored sentry.

    tools/enemy_model.py assets/enemy/enemy.yaml OUT_DIR

Writes OUT_DIR/enemy_mujoco.urdf and OUT_DIR/enemy_achilles.urdf: the
doctored sentry URDFs (tools/doctor_urdf.py) with the field, the floating
base and the omni rollers removed, every joint welded, each wheel given a
plain cylinder to collide with (its rollers did), and the armor light bars
in the enemy's team colour. Its root link is base_footprint, so the hub
places it as enemy/base_footprint (a MuJoCo attach element's mocap body, the
Achilles archetype `enemy`'s welded root). Standard library and PyYAML.
"""
import argparse
import copy
import math
import os
import sys
import xml.etree.ElementTree as ET

import yaml

TEAM = {"blue": "0.1 0.35 1 1", "red": "1 0.15 0.1 1"}


def rpy_with_z_along(axis):
    """rpy turning a frame's z onto `axis` (a unit vector)."""
    x, y, z = axis
    pitch = math.atan2(math.hypot(x, y), z)
    yaw = math.atan2(y, x)
    return f"0 {pitch:.9g} {yaw:.9g}"


def build(src, out, team_rgba, wheel):
    tree = ET.parse(src)
    robot = tree.getroot()
    robot.set("name", "enemy")
    links = {l.get("name"): l for l in robot.findall("link")}
    joints = robot.findall("joint")

    # The field (the world link) and the floating base: the hub places the
    # robot instead.
    floating = [j for j in joints if j.get("type") == "floating"]
    if len(floating) != 1:
        raise SystemExit(f"enemy_model: {src} needs one floating joint, has {len(floating)}")
    if floating[0].find("child").get("link") != "base_footprint":
        raise SystemExit(f"enemy_model: {src}'s floating base carries {floating[0].find('child').get('link')}, "
                         "not base_footprint")
    robot.remove(floating[0])
    robot.remove(links.pop("world"))

    # The omni rollers: a kinematic robot doesn't roll; each wheel collides
    # as a plain cylinder about its axle instead.
    for j in [j for j in robot.findall("joint") if "_roller_" in j.find("child").get("link")]:
        robot.remove(j)
    for name in [n for n in links if "_roller_" in n]:
        robot.remove(links.pop(name))
    for j in robot.findall("joint"):
        child = j.find("child").get("link")
        if child not in wheel["wheels"]:
            continue
        axis = [float(v) for v in j.find("axis").get("xyz").split()]
        n = math.sqrt(sum(v * v for v in axis))
        link = links[child]
        for c in link.findall("collision"):
            link.remove(c)
        col = ET.SubElement(link, "collision", name=f"{child}_rim")
        ET.SubElement(col, "origin", xyz="0 0 0", rpy=rpy_with_z_along([v / n for v in axis]))
        ET.SubElement(ET.SubElement(col, "geometry"), "cylinder", radius=f"{wheel['wheel_radius']:.9g}",
                      length=f"{wheel['row_spacing'] + 2 * wheel['roller_radius']:.9g}")
        for cyl in link.iter("cylinder"):  # the drawn hub (Achilles) out to the rim
            cyl.set("radius", f"{wheel['wheel_radius']:.9g}")

    # Every joint welded: nothing on it moves but the whole robot.
    for j in robot.findall("joint"):
        j.set("type", "fixed")
        for tag in ("axis", "limit", "dynamics", "mimic", "safety_controller", "calibration"):
            for el in j.findall(tag):
                j.remove(el)
    for t in robot.findall("transmission"):
        robot.remove(t)

    # Its team's light bars.
    bars = 0
    for link in robot.findall("link"):
        for v in link.findall("visual"):
            if "_bar_" in (v.get("name") or ""):
                for color in v.iter("color"):
                    color.set("rgba", team_rgba)
                    bars += 1
    if not bars:
        raise SystemExit(f"enemy_model: no armor light bars (visuals named *_bar_*) in {src}")

    ET.indent(tree, space="  ")
    with open(out, "w") as f:
        f.write(f"<?xml version=\"1.0\"?>\n<!-- Generated by tools/enemy_model.py from {os.path.relpath(src, os.path.dirname(out))}"
                " and assets/enemy/enemy.yaml. Don't edit: regenerate it. -->\n")
        tree.write(f, encoding="unicode")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("spec")
    ap.add_argument("out_dir")
    args = ap.parse_args()
    spec_dir = os.path.dirname(os.path.abspath(args.spec))
    with open(args.spec) as f:
        spec = yaml.safe_load(f)
    if spec["team_color"] not in TEAM:
        raise SystemExit(f"enemy_model: team_color is red or blue, not {spec['team_color']!r}")
    source = os.path.normpath(os.path.join(spec_dir, spec["source"]))
    with open(os.path.join(os.path.dirname(spec_dir), "sentry", "urdf_doctor.yaml")) as f:
        wheel = yaml.safe_load(f)["omni_wheels"]
    os.makedirs(args.out_dir, exist_ok=True)
    for variant in ("mujoco", "achilles"):
        src = os.path.join(source, f"sentry_{variant}.urdf")
        out = os.path.join(args.out_dir, f"enemy_{variant}.urdf")
        build(src, out, TEAM[spec["team_color"]], wheel)
        print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
